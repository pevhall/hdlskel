"""Generate `version.hpp` for the hdlskel skmap C++ library.

The skmap version constants live in `skmap.basic_types` (single source of
truth). This module emits the matching C++ constants into
`sw/lib/cpp/skmap/include/hdlskel/skmap/version.hpp` so the C++ library can
never drift from the python library.

Can be used as a script:

    python -m skmap.code_generator_version_hpp \
        sw/lib/cpp/skmap/include/hdlskel/skmap/version.hpp
    python code_generator_version_hpp.py --check <path>

or from python:

    from skmap.code_generator_version_hpp import generate_version_hpp
    generate_version_hpp(Path("sw/lib/cpp/skmap/include/hdlskel/skmap/version.hpp"))
"""

import logging
import sys
from datetime import datetime
from pathlib import Path
from typing import Optional

from .basic_types import (
    SKMAP_VER_MAJOR,
    SKMAP_VER_MINOR,
    SKMAP_VER_PATCH,
    SKMAP_VER_STR,
)
from .code_generator_all_hpp import strip_header

log = logging.getLogger(__name__)

VERSION_HPP_NAME = "version.hpp"

def version_hpp_content() -> str:
    """Full contents of version.hpp generated from the python constants."""
    return f"""//-------------------------------------------------------------------------------
// NOTE: this file is autogenerated (do not edit):
//    * From {__file__}
//    * On {datetime.now()}
//    * Single source of truth: pip/skmap/src/skmap/basic_types.py
//    * Using HDLSkel SkMap {SKMAP_VER_STR}
//-------------------------------------------------------------------------------
#pragma once

#include <string>

namespace hdlskel::skmap {{

constexpr int ver_major = {SKMAP_VER_MAJOR};
constexpr int ver_minor = {SKMAP_VER_MINOR};
constexpr int ver_patch = {SKMAP_VER_PATCH};
// Matches python SKMAP_VER_STR (note the 'v' prefix).
const std::string ver_str = "{SKMAP_VER_STR}";

}}
"""

def generate_version_hpp(
    hpp_file    : Path,
    dry_run     : bool = False,
    show        : bool = False,
    force       : bool = False,
) -> bool:
    """Write version.hpp to `hpp_file`.

    Returns True if the file content changed (or would change with dry_run).
    Existing content is left untouched when identical unless force is set.
    """
    content = version_hpp_content()
    # Ignore the autogenerated banner (it carries a timestamp) when comparing.
    changed = (not hpp_file.exists()) or \
        (strip_header(hpp_file.read_text()) != strip_header(content))
    if show:
        sys.stdout.write(content)
    if dry_run or (not changed and not force):
        log.info("%s: %s", hpp_file, "would change" if changed else "up to date")
        return changed
    hpp_file.parent.mkdir(parents=True, exist_ok=True)
    hpp_file.write_text(content)
    log.info("Wrote %s", hpp_file)
    return changed
