"""Generate an `all.hpp` umbrella header for a directory of C++ headers.

Scans a directory for `*.hpp` files (excluding `all.hpp` itself) and writes an
`all.hpp` next to them that simply `#include`s every scanned header.

Can be used as a script:

    python -m skmap.code_generator_all_hpp sw/lib/cpp/skmap/include/hdlskel/skmap
    python code_generator_all_hpp.py -r --check some/dir

or from python:

    from skmap.code_generator_all_hpp import generate_all_hpp
    generate_all_hpp("sw/lib/cpp/skmap/include/hdlskel/skmap")
"""

import fnmatch
import logging
from datetime import datetime
from pathlib import Path
from typing import Iterable, Optional, Sequence

try:  # when imported as part of the skmap package
    from .basic_types import SKMAP_VER_STR
except ImportError:  # when run as a plain script
    try:
        from skmap.basic_types import SKMAP_VER_STR  # type: ignore
    except ImportError:
        SKMAP_VER_STR = "unknown"

log = logging.getLogger(__name__)

ALL_HPP_NAME = "all.hpp"


def file_header(source: Path, target: Path) -> str:
    return (
        "//-------------------------------------------------------------------------------\n"
        "// NOTE: this file is autogenerated:\n"
        f"//    * From {source}\n"
        f"//    * On {datetime.now()}\n"
        f"//    * Using HDLSkel SkMap {SKMAP_VER_STR}\n"
        f"//    * For {target}\n"
        "//-------------------------------------------------------------------------------\n"
    )


def is_excluded(rel_path: Path, patterns: Sequence[str] = ()) -> bool:
    """True if `rel_path` (relative to the scan root) matches any of the `patterns`.

    A pattern may match the file name (`*Types.hpp`), the whole relative path
    (`internal/*`) or any ancestor directory name (`build`).
    """
    for pattern in patterns:
        if fnmatch.fnmatch(rel_path.name, pattern):
            return True
        if fnmatch.fnmatch(rel_path.as_posix(), pattern):
            return True
        if any(fnmatch.fnmatch(part, pattern) for part in rel_path.parts[:-1]):
            return True
    return False


def scan_hpp_files(
    directory: Path,
    recursive: bool = True,
    exclude: Sequence[str] = (),
) -> list[Path]:
    """Return a sorted list of `*.hpp` files in `directory`, excluding `all.hpp`.

    Returns absolute paths. Anything named `all.hpp` is skipped, as are files matched
    by `exclude`.
    """
    directory = directory.resolve()
    if not directory.is_dir():
        raise NotADirectoryError(f"Not a directory: {directory}")

    pattern = "**/*.hpp" if recursive else "*.hpp"
    hpp_files: list[Path] = []
    for hpp in directory.glob(pattern):
        if not hpp.is_file():
            continue
        rel = hpp.resolve().relative_to(directory)
        if hpp.name == ALL_HPP_NAME:
            continue
        if is_excluded(rel, exclude):
            log.debug(f"skipping (excluded): {hpp}")
            continue
        hpp_files.append(hpp.resolve())

    hpp_files.sort(key=lambda p: p.relative_to(directory).as_posix().lower())
    return hpp_files


def include_str(hpp_file: Path, root: Path, prefix: str = "") -> str:
    """`#include "..."` line for `hpp_file`, relative to the scan `root`."""
    rel = hpp_file.resolve().relative_to(root.resolve()).as_posix()
    if prefix:
        rel = f"{prefix.rstrip('/')}/{rel}"
    return f'#include "{rel}"'


def make_all_hpp_content(
    hpp_files: Iterable[Path],
    root: Path,
    prefix: str = "",
    header: Optional[str] = None,
) -> str:
    includes = "\n".join(include_str(hpp, root, prefix) for hpp in hpp_files) or "// (no *.hpp files found)"
    if header is None:
        header = file_header(Path(__file__), root / ALL_HPP_NAME)
    return f"{header}\n#pragma once\n\n{includes}\n"


def generate_all_hpp(
    directory: Path | str,
    recursive: bool = False,
    exclude: Sequence[str] = (),
    prefix: str = "",
    dry_run: bool = False,
    show: bool = True,
    force: bool = False,
) -> tuple[Path, bool]:
    """Scan `directory` for `*.hpp` files and write `all.hpp` into it.

    Returns `(all_hpp_path, changed)` where `changed` is True when an up-to-date
    `all.hpp` would have to be (re)written. Nothing is written when `dry_run` is set,
    the generated content is printed when `dry_run` and `show` are both set, and the
    file is only rewritten when its content changes, unless `force` is set.
    """
    root = Path(directory).resolve()
    hpp_files = scan_hpp_files(root, recursive=recursive, exclude=exclude)
    all_hpp = root / ALL_HPP_NAME
    content = make_all_hpp_content(hpp_files, root, prefix=prefix)

    log.info(f"Scanned {root} -> {len(hpp_files)} header(s)")
    for hpp in hpp_files:
        log.debug(f"  include {hpp.relative_to(root).as_posix()}")

    existing = all_hpp.read_text() if all_hpp.exists() else None
    if (not force) and existing is not None and strip_header(existing) == strip_header(content):
        log.info(f"up to date: {all_hpp}")
        return all_hpp, False

    if dry_run:
        if show:
            print(f"--- {all_hpp} (dry run) ---")
            print(content, end="")
        return all_hpp, True

    all_hpp.write_text(content)
    log.info(f"{'overwritten' if existing is not None else 'created'}: {all_hpp}")
    return all_hpp, True


def strip_header(text: str) -> str:
    """Drop the autogenerated banner so content comparison ignores the timestamp."""
    lines = text.splitlines()
    if lines and lines[0].startswith("//---"):
        for ii, line in enumerate(lines):
            if line.startswith("//---") and ii > 0:
                return "\n".join(lines[ii + 1:]).strip()
    return text.strip()


